"""Stream models for Kafka message contracts and alerts.

Defines Pydantic models for Kafka messages that are exported to JSON Schema
files. This supports data contracts that can be validated both in code and
externally via JSON Schema.
"""

from typing import Literal

from pydantic import BaseModel, Field


# Weather Current Contract (Appendix C)
class WeatherCurrentV1(BaseModel):
    """Model for current weather data sent to Kafka topic `weather.current.raw`.

    Fields align with the specification in Appendix C of the
    project documentation. The model is used both for validation and for
    generating JSON Schema documentation.
    """

    event_id: str = Field(..., description="UUID string, required, unique")
    schema_version: Literal["1.0"] = Field(..., description='must be "1.0"')
    kode_provinsi_bps: str = Field(
        ..., description="province code, required, must exist in ref.ref_provinsi"
    )
    observed_at: str = Field(
        ..., description="datetime with timezone, required, not more than 1 hour in the future"
    )
    temperature_c: float | None = Field(
        None, ge=-10, le=50, description="temperature in Celsius, range -10 to 50"
    )
    precipitation_mm: float | None = Field(
        None, ge=0, le=500, description="precipitation in mm, range 0-500"
    )
    humidity_pct: float | None = Field(
        None, ge=0, le=100, description="relative humidity percentage, 0-100"
    )
    wind_speed_kph: float | None = Field(
        None, ge=0, description="wind speed in kilometers per hour, non-negative"
    )
    wind_direction_deg: int | None = Field(
        None, ge=0, le=360, description="wind direction degrees, 0-360"
    )
    cloud_cover_pct: int | None = Field(
        None, ge=0, le=100, description="cloud cover percentage, 0-100"
    )
    visibility_km: float | None = Field(
        None, gt=0, description="visibility in kilometers, positive"
    )
    pressure_hpa: float | None = Field(
        None, description="atmospheric pressure in hectopascals, reasonable range"
    )
    uv_index: int | None = Field(None, ge=0, description="UV index, 0-11+")
    sunrise_at: str | None = Field(None, description="sunrise time with timezone")
    sunset_at: str | None = Field(None, description="sunset time with timezone")
    moon_phase: float | None = Field(None, description="moon phase fraction, 0-1")
    rain_mm: float | None = Field(
        None,
        ge=0,
        description="Appendix C: liquid rain only (subset of precipitation_mm), mm, non-negative",
    )
    weather_code: int | None = Field(
        None, ge=0, le=99, description="Appendix C: WMO weather interpretation code, 0-99"
    )
    source: Literal["open-meteo"] = Field(
        "open-meteo", description="Appendix C: data source, must be 'open-meteo'"
    )
    fetched_at: str = Field(
        ...,
        description="Appendix C: datetime with timezone when the producer fetched this reading, required",
    )
    producer_id: str = Field(
        ...,
        description="Appendix C: identifier of the producer instance that sent this message, required",
    )

    @classmethod
    def schema(cls, **kwargs):
        """Generate JSON Schema for this model.

        This method is used by the `make contracts` Makefile target to export
        the model definitions to `contracts/weather_current_v1.json`.
        """
        # Pydantic v2 way to get schema
        config = kwargs.pop("config", None)
        schema = cls.model_json_schema(config=config, **kwargs)
        return schema

    @classmethod
    def model_json_schema(cls, **kwargs):
        # Custom title for the schema
        _ = kwargs.pop("config", None)
        schema = super().model_json_schema(**kwargs)
        schema["title"] = "WeatherCurrentV1"
        return schema


# Weather Alert Contract
class WeatherAlertV1(BaseModel):
    """Model for weather alerts sent to Kafka topic `weather.alert`.

    Fields align with the alert contract used when precipitation exceeds a
    configured threshold. Alerts are generated by the Kafka consumer when
    conditions in `settings.yaml` trigger.
    """

    event_id: str = Field(..., description="UUID string, required, unique")
    schema_version: Literal["1.0"] = Field(..., description='must be "1.0"')
    kode_provinsi_bps: str = Field(..., description="province code, required")
    alert_type: str = Field(..., description="type of alert, e.g., heavy_rain")
    alert_level: Literal["light", "moderate", "heavy", "extreme"] = Field(
        ..., description="severity level"
    )
    threshold_field: str = Field(..., description="field that triggered the alert")
    threshold_value: float = Field(..., description="configured threshold value")
    current_value: float = Field(..., description="current observed value")
    observed_at: str = Field(..., description="observation timestamp with timezone")
    valid_until: str | None = Field(None, description="alert valid until timestamp")
    recommendation: str | None = Field(None, description="recommendation text")

    @classmethod
    def model_json_schema(cls, **kwargs):
        _ = kwargs.pop("config", None)
        schema = super().model_json_schema(**kwargs)
        schema["title"] = "WeatherAlertV1"
        return schema
